import pandas as pd

URL = 'http://fpaniaguapython.github.io/datos/CCAA-ULTIMOS-DOCE-MESES-LAPTOP-H55DSDJ2-2026-09.csv'

df = pd.read_csv(URL, sep=';', thousands='.')

display(df.info())
display(df.describe())
display(df.head())

"""## Hacemos una copia del df"""

df_original = df.copy()

"""## Convertimos la columna comunidad en índice"""

#df.index = df['comunidad']
df.set_index('comunidad', inplace=True)
df.head()

"""## Eliminamos la fila de totales (Total)"""

df = df.drop('Total')
df.head()

"""## Se muestra un diagrama de barras con las matriculaciones de una comunidad"""

while True:
  comunidad = input('COMUNIDAD:')
  comunidad = comunidad.strip().upper()
  if comunidad in df.index:
    df.loc[comunidad].plot(kind='bar', title=comunidad)
    break
  else:
    print(f'Error. Los valores posibles son {df.index}')

"""## Se muestra un diagrama de barras con las matriculaciones de un mes"""

df['ene-26'].plot(kind='bar', title='ene-26')

"""## Boxplot de ene-26"""

df['ene-26'].plot(kind='box', title='ene-26', vert=False)

"""## Histograma"""

df['ene-26'].plot(kind='hist', title='ene-26', bins=5)