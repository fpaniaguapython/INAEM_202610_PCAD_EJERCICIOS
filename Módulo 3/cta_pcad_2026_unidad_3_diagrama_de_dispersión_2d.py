"""## Distribución uniforme, 2 variable"""

# Configurar la semilla para reproducibilidad
np.random.seed(42)

# Crear un dataset con 1000 valores por variable con distribución uniforme
data = {
    'X': np.random.uniform(low=0, high=100, size=1000),
    'Y': np.random.uniform(low=0, high=100, size=1000)
}

df = pd.DataFrame(data)

# Creamos el diagrama de dispersión

plt.scatter(df['X'], df['Y'], color='skyblue', alpha=0.5)

plt.title('Diagrama de Dispersión con distribución uniforme Matplotlib')
plt.xlabel('X')
plt.ylabel('Y')
plt.grid(True)

plt.show()

