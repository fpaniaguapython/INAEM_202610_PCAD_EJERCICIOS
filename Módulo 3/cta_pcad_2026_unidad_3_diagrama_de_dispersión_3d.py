import pandas as pd
import numpy as np

import matplotlib.pyplot as plt

"""## Tendencia uniforme"""

# Configurar la semilla para reproducibilidad
np.random.seed(42)

# Crear un dataset con 1000 valores por variable con distribución uniforme
data = {
    'X': np.random.uniform(low=0, high=100, size=1000),
    'Y': np.random.uniform(low=0, high=100, size=1000),
    'Z': np.random.uniform(low=0, high=100, size=1000)
}

df = pd.DataFrame(data)
display(df.head())
print(f"Dimensiones del dataset: {df.shape}")

# Crear un diagrama de dispersión 3D
fig = plt.figure(figsize=(10, 8))
ax = fig.add_subplot(111, projection='3d')

# Dibujar los puntos
scatter = ax.scatter(df['X'], df['Y'], df['Z'], c=df['Z'], cmap='viridis', s=60, edgecolors='k')

# Configurar etiquetas y título
ax.set_title('Diagrama de Dispersión 3D (Distribución Uniforme)', fontsize=14, pad=20)
ax.set_xlabel('Eje X')
ax.set_ylabel('Eje Y')
ax.set_zlabel('Eje Z')

# Añadir una barra de colores de referencia para el eje Z
colorbar = fig.colorbar(scatter, ax=ax, shrink=0.5, aspect=10)
colorbar.set_label('Valores de Z')

plt.tight_layout()
plt.show()

"""## Tendencia gaussiana"""

# Configurar la semilla para reproducibilidad
np.random.seed(42)

# Crear un dataset con 1000 valores por variable con distribución uniforme
data = {
    'X': np.random.normal(loc=0, scale=1, size=1000),
    'Y': np.random.normal(loc=0, scale=1, size=1000),
    'Z': np.random.normal(loc=0, scale=1, size=1000)
}

df = pd.DataFrame(data)
display(df.head())
print(f"Dimensiones del dataset: {df.shape}")

# Crear un diagrama de dispersión 3D
fig = plt.figure(figsize=(10, 8))
ax = fig.add_subplot(111, projection='3d')

# Dibujar los puntos
scatter = ax.scatter(df['X'], df['Y'], df['Z'], c=df['Z'], cmap='viridis', s=60, edgecolors='k')

# Configurar etiquetas y título
ax.set_title('Diagrama de Dispersión 3D (Distribución Normal)', fontsize=14, pad=20)
ax.set_xlabel('Eje X')
ax.set_ylabel('Eje Y')
ax.set_zlabel('Eje Z')

# Añadir una barra de colores de referencia para el eje Z
colorbar = fig.colorbar(scatter, ax=ax, shrink=0.5, aspect=10)
colorbar.set_label('Valores de Z')

plt.tight_layout()
plt.show()

"""## Diagrama de dispersión 3D **interactivo** con distribución normal utilizando **PLOTLY EXPRESS**"""

import plotly.express as px

# Crear gráfico 3D interactivo con Plotly
fig_interactive = px.scatter_3d(
    df,
    x='X',
    y='Y',
    z='Z',
    color='Z',
    color_continuous_scale='viridis',
    title='Diagrama de Dispersión 3D Interactivo (Rotable con el Ratón)'
)

# Ajustar el tamaño del gráfico
fig_interactive.update_layout(width=800, height=600)
fig_interactive.show()