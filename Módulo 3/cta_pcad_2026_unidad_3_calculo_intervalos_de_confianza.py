## Distribución normal (se conoce la desviación estándar)
"""

import numpy as np
import scipy.stats as st
# Simulamos una muestra grande (1000 usuarios)
np.random.seed(42) # Para que siempre dé el mismo resultado
datos_grandes = np.random.normal(loc=5, scale=1.5, size=1000)

media = np.mean(datos_grandes)
error_estandar = st.sem(datos_grandes)
nivel_confianza = 0.95

# Calculamos usando la distribución Normal (no requiere  grados de libertad)
intervalo_z = st.norm.interval(confidence=nivel_confianza, loc=media,  scale=error_estandar)

print(f"Media de la muestra grande: {media:.2f}")
print(f"Intervalo de confianza del 95% (Z): {intervalo_z}")

"""## Distribución t de Student (la desviación estándar es estimada)"""

import numpy as np
import scipy.stats as st

# 1. Creamos unos datos de ejemplo (por ejemplo, horas de uso del móvil)
datos = [4.5, 5.2, 6.0, 4.8, 5.1, 4.3, 5.5, 4.9, 5.2, 4.7]

# 2. Calculamos los datos básicos de la muestra
media = np.mean(datos)
error_estandar = st.sem(datos) # Error estándar de la media (SEM)
grados_libertad = len(datos) - 1
nivel_confianza = 0.95

# 3. Calculamos el intervalo de confianza
intervalo = st.t.interval(confidence=nivel_confianza,
  df=grados_libertad,
  loc=media,
  scale=error_estandar)

print(f"Media de la muestra: {media:.2f}")
print(f"Intervalo de confianza del 95%: {intervalo}")