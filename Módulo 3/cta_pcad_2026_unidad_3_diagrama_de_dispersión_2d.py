import pandas as pd
import numpy as np
import matplotlib.pyplot as plt
import plotly.express as px

"""## Distribución uniforme, 1 variable


"""

# Configurar la semilla para reproducibilidad
np.random.seed(42)

# Crear un dataset con 1000 valores por variable con distribución uniforme
data = np.random.uniform(low=0, high=100, size=1000)

series = pd.Series(data)

# Histograma con Matplotlib
plt.figure(figsize=(10, 5))
plt.hist(series, bins=25, color='skyblue', edgecolor='black')

plt.title('Histograma con Matplotlib')
plt.xlabel('Valores')
plt.ylabel('Frecuencia')
plt.grid(axis='y', alpha=0.3)

plt.show()

# Histograma con Plotly Express
fig = px.histogram(
    series,
    nbins=25,
    title='Histograma con Plotly Express',
    labels={'value': 'Valores', 'count': 'Frecuencia'}
)

fig.update_traces(
    marker_color='skyblue',
    marker_line_color='black',
    marker_line_width=0.5
)

fig.update_layout(
    xaxis_title='Valores',
    yaxis_title='Frecuencia',
    bargap=0.05
)

fig.show()

