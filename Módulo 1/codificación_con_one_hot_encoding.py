import pandas as pd

# Crear un DataFrame de ejemplo
df = pd.DataFrame({
    'Nombre': ['Juan', 'María', 'Pedro', 'Ana', 'Luis'],
    'Edad': [25, 30, 35, 40, 45],
    'Color': ['Rojo', 'Azul', 'Verde', 'Rojo', 'Azul'],
    'Idioma': ['Inglés', 'Inglés', 'Italiano', 'Chino', 'Chino']
})

print(df)

df_encoded = pd.get_dummies(data=df, columns=['Color', 'Idioma'], dtype=int)

print(df_encoded)