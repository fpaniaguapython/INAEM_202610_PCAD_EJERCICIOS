from google.colab import userdata
import pandas as pd
import requests

# Obteniendo el API_KEY del área de secretos de colab
API_KEY = userdata.get('OMDB_API')
# Solicitamos información al usuario
titulo = input('Título:')
# Montamos la URL utilizando f-string
url = f'https://www.omdbapi.com/?apikey={API_KEY}&t={titulo}'
display(url)

# Hacemos la petición
response = requests.get(url)

# Evaluar si la petición se ha resuelto satisfactoriamente
if response.status_code == 200:
  movie = response.json()
  df_movie = pd.json_normalize(movie)
  display(df_movie)
else:
  print(f'Ha ocurrido un error {response.status_code}')