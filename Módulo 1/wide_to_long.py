## Conversión de wide a long utilizando la función pd.melt
"""

import pandas as pd

wide_data = {
    'year': [2023, 2024, 2025],
    'Alice': [50000, 60000, 70000],
    'Bob': [55000, 65000, 75000],
    'Charlie': [60000, 70000, 80000],
    'David': [65000, 75000, 85000]
}

wide_df = pd.DataFrame(wide_data)

display(wide_df)

"""## Conversión en formato long utilizando pd.melt"""

long_df = pd.melt(
    frame=wide_df,
    id_vars = 'year',
    var_name = 'employee',
    value_name = 'salary')

display(long_df)

"""## Salarios de Alice"""

long_df.loc[long_df['employee'] == 'Alice', 'salary']

"""## Medias por empleado"""

df_media = long_df.groupby("employee")["salary"].mean()
