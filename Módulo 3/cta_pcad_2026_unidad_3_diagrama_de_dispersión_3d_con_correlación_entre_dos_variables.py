import pandas as pd
import numpy as np

import matplotlib.pyplot as plt

"""## Generación de datos"""

# Configurar la semilla para reproducibilidad
np.random.seed(42)

# Crear X con distribución uniforme
X = np.random.uniform(low=0, high=100, size=1000)

# Crear Y fuertemente relacionada con X
# Se añade un pequeño ruido para evitar una relación perfecta
Y = X + np.random.normal(loc=0, scale=10, size=1000)

# Mantener los valores de Y dentro del intervalo [0, 100]
Y = np.clip(Y, 0, 100)

# Crear Z con distribución uniforme e independiente
#Z = np.random.uniform(low=0, high=100, size=1000)

# Crear Z con distribución normal e independiente
Z = np.random.normal(loc=0, scale=1.0, size=1000)

# Crear el DataFrame
data = {
    'X': X,
    'Y': Y,
    'Z': Z
}

df = pd.DataFrame(data)

display(df.head())
print(f"Dimensiones del dataset: {df.shape}")

# Comprobar las correlaciones
print("\nMatriz de correlación:")
display(df.corr())

import seaborn as sns

# Crear matriz de dispersión 3x3
sns.pairplot(
    df[['X', 'Y', 'Z']],
    diag_kind='hist',
    plot_kws={'alpha': 0.5, 's': 20}
)

plt.suptitle('Matriz de dispersión de X, Y y Z', y=1.02)
plt.show()

plt.figure(figsize=(7, 5))

sns.heatmap(
    df[['X', 'Y', 'Z']].corr(),
    annot=True,
    cmap='coolwarm',
    fmt='.1f'
)

plt.title('Matriz de correlación')
plt.show()

import plotly.express as px

# Crear gráfico 3D interactivo con Plotly
fig_interactive = px.scatter_3d(
    df,
    x='X',
    y='Y',
    z='Z',
    color='Z',
    color_continuous_scale='viridis',
    title='Diagrama de Dispersión 3D Interactivo (Rotable con el Ratón)'
)

# Ajustar el tamaño del gráfico
fig_interactive.update_layout(width=800, height=600)
fig_interactive.show()