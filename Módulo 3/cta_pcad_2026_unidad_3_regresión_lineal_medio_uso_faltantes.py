import pandas as pd
import numpy as np
import joblib # Módulo para el almacenamiento de los modelos serializados
from google.colab import drive
drive.mount('/content/drive') # Montamos la unidad de Google Drive

"""## Lectura del modelo"""

modelo = joblib.load('/content/drive/MyDrive/modelo_colesterol.pkl')

"""## Lectura de los datos"""

URL = 'http://fpaniaguapython.github.io/datos/datos_regresion_lineal_faltantes.csv'
df = pd.read_csv(URL)
df.head()

# Cambio de índices
df.set_index('id', inplace=True)
# Elilminar la columna de profesión
df.drop('profesion', axis=1, inplace=True)
# Convierta las variables categóricas en numéricas
df = pd.get_dummies(df)
# Obtener las filas que tienen valores NaN
df_sin_colesterol = df[df.isna().any(axis=1)]
# Eliminamos la columna del colesterol
data = df_sin_colesterol.drop('colesterol', axis=1)
display(data)
# Calculamos las predicciones
predicciones = modelo.predict(data)
display(predicciones)
# Asignamos las predicciones a la columna colesterol del df_sin_colesterol
df_sin_colesterol['colesterol'] = predicciones
display(df_sin_colesterol)
# Asignamos los valores del df_sin_colesterol al df original
df.update(df_sin_colesterol)
display(df)

