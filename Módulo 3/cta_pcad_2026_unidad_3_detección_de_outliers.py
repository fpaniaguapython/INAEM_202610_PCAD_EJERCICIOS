import pandas as pd
import matplotlib.pyplot as plt

data = [1.7, 1.8, 1.72, 1.65, 1.61, 2.15, 1.81, 1.70]

serie = pd.Series(data)

"""## Boxplot"""

plt.boxplot(serie, vert=False)
plt.title("Boxplot")
plt.xlabel("Altura (m)")
plt.show()