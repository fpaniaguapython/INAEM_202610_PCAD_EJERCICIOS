import pandas as pd
import sqlite3
import ipywidgets as widgets
from IPython.display import display

"""## Establecimiento de la conexión"""

conn = sqlite3.connect('db_empleados_optimizado.sqlite3')

"""## Leer las categorías profesionales"""

categorias_profesionales = pd.read_sql_query(
    'SELECT DISTINCT categoria_profesional FROM empleados', conn)
display(categorias_profesionales)

"""## Solicitud de datos al usuario (incluye dropdown)"""

ciudad = input('Introduce la ciudad:')
salario_maximo = input('Introduce el salario máximo:')
desplegable = widgets.Dropdown(
    options=categorias_profesionales['categoria_profesional'].tolist(),
    description='Categorias profesionales:',
    value=categorias_profesionales['categoria_profesional'].iloc[0],
    layout={'width': '300px'}
)
display(desplegable)

"""## Obtención de los datos mediante una sentencia SQL"""

categoria_profesional = desplegable.value
display(categoria_profesional)
#sql = 'SELECT * FROM empleados WHERE ciudad LIKE ? AND salario<? AND categoria_profesional=?'
#df = pd.read_sql_query(sql, conn, params=(f'%{ciudad}%', salario_maximo, categoria_profesional))
sql = 'SELECT * FROM empleados WHERE ciudad=? AND salario<? AND categoria_profesional=?'
df = pd.read_sql_query(sql, conn, params=(ciudad, salario_maximo, categoria_profesional))
display(df.head())
display(df.info())

"""## Almacenamiento de datos en un fichero CSV"""

df.to_csv('empleados_filtrados.csv', index=False)

"""## Filtro"""

empleados_carlos = df[df['nombre']=='Carlos']
display(empleados_carlos)

# Filtramos los salarios < 30000

df_salarios_bajos = df[(df['salario']>25000) & (df['salario']<30000)]
display(df_salarios_bajos)

"""## Ordenación del DataFrame"""

empleados_ordenados = df.sort_values(by='salario', ascending=False)
display(empleados_ordenados)

"""## Detección de nulos"""

display(df.isnull())

"""## Eliminación de nulos (valores faltantes)"""

df_sin_faltantes = df.dropna(inplace=False) # De todo el DataFrame
df_nombres_sin_faltantes = df['apellidos'].dropna(inplace=False) # Solo de la columna apellidos
display(df_sin_faltantes.head())
display(df_nombres_sin_faltantes.head())

"""## Reemplazo de valores faltantes"""

df.fillna(value='No disponible', inplace=True)

"""# Eliminar inconsistencias"""

df['ciudad'] = df['ciudad'].str.upper()
