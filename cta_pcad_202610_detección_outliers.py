## Z-SCORE con PANDAS
"""

import pandas as pd
# Serie de datos
datos = [10, 12, 14, 15, 18, 10, 12, 140, 150, 18, 10, 12, 14, 15, 18, 100]
# Crear Series de pandas
s = pd.Series(datos)
# Calcular media y desviación estándar
media = s.mean()
std = s.std()
# Calcular z-score
z_scores = (s - media) / std
# Umbral para outliers
umbral = 2
# Detectar outliers
outliers = s[z_scores.abs() > umbral]
# Mostrar resultados
print("Z-scores:")
print(z_scores)
print("\nPosibles outliers:")
print(outliers.values)

"""## Detección de outliers con Z-Score con Numpy"""

import numpy as np
# Serie de datos
datos = [10, 12, 14, 15, 18, 10, 12, 14, 15, 18, 10, 12, 14, 15, 18, 100]
# Convertir a array de NumPy
datos_np = np.array(datos)
# Calcular media y desviación estándar
media = np.mean(datos_np)
desviacion = np.std(datos_np)
# Calcular z-scores
z_scores = (datos_np - media) / desviacion
# Umbral típico para detectar outliers
umbral = 2
# Encontrar posibles outliers
outliers = datos_np[np.abs(z_scores) > umbral]
# Mostrar resultados
print("Media:", media)
print("Desviación estándar:", desviacion)
print("Z-scores:")
print(z_scores)
print("\nPosibles outliers:")
print(outliers)

"""## Detección de outliers con Z-Score con Numpy+Scipy"""

import numpy as np
from scipy.stats import zscore
# Serie de datos
datos = [10, 12, 14, 15, 18, 10, 12, 14, 15, 18, 10, 12, 14, 15, 18, 100]

# Convertir a array de NumPy
datos_np = np.array(datos)
# Calcular z-scores con SciPy
z_scores = zscore(datos_np)
# Umbral típico para detectar outliers
umbral = 2
# Detectar posibles outliers
outliers = datos_np[np.abs(z_scores) > umbral]
# Mostrar resultados
print("Z-scores:")
print(z_scores)
print("\nPosibles outliers:")
print(outliers)