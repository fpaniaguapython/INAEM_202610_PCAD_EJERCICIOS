import pandas as pd

"""## Crear un fichero (principios.txt) con la lista de principios activos siguiente y almacenarla en la zona de almacenamiento de Colab

* Paracetamol
* Ibuprofeno
* Ácido acetilsalicílico
* Omeprazol
* Amoxicilina
* Loratadina
* Cetirizina
* Metformina
* Loperamida
* Diclofenaco
"""

principios_activos = [
    "Paracetamol",
    "Ibuprofeno",
    "Ácido acetilsalicílico",
    "Omeprazol",
    "Amoxicilina",
    "Loratadina",
    "Cetirizina",
    "Metformina",
    "Loperamida",
    "Diclofenaco"
]
with open('principios.txt', mode='wt', encoding='utf-8') as fichero_principios:
  for principio_activo in principios_activos:
    fichero_principios.write(f"{principio_activo}\n")

"""## Función de validación de días de la semana"""

def validar_dia_semana(dia_a_verificar: str) -> bool:
    DIAS_SEMANA = ['LUNES', 'MARTES', 'MIÉRCOLES', 'JUEVES', 'VIERNES']
    es_valido = dia_a_verificar in DIAS_SEMANA
    return es_valido

"""## Función de validación de los principios activos"""

principios_activos = None

def leer_principios_activos(nombre_fichero: str) -> list:
    with open(nombre_fichero, mode='rt', encoding='utf-8') as fichero:
        principios_activos = fichero.readlines()
    principios_activos = [principio_activo.strip() for principio_activo in principios_activos]
    return principios_activos

if principios_activos is None:
  principios_activos = leer_principios_activos('principios.txt')

def validar_principios_activos(principios_activos: list, principio_activo: str) -> bool:
    principio_valido = principio_activo in principios_activos
    return principio_valido

"""## Dataset"""

pedido = {
    "id_pedido": [1, 2, 3, 4, 5, 6],
    "dia_entrega": ["LUNES", "MARTES", "MIÉRCOLES", "MARTES", "JUEVES", "SÁBADO"],
    "id_cliente": [101, 102, 103, 104, 105, 106],
    "principio_activo": ["Loperamida", "Diclofenaco", "Ibuprofeno", "Paracetamol", "Gaseosa", "Metformina"]
}
df = pd.DataFrame(pedido)
display(df)

"""## Comprobar que todos los días de las semana son válidos"""

dias_semana_correctos = df['dia_entrega'].apply(validar_dia_semana).all()
display(dias_semana_correctos)

"""## Comprobar que todos los principios activos son válidos"""

principios_correctos = df['principio_activo'].apply(
    lambda principio : validar_principios_activos(principios_activos, principio)).all()
display(principios_correctos)

"""## Obtener los valores válidos de días de las semana

> Añadir blockquote


"""

df_dias_validos = df[df['dia_entrega'].apply(validar_dia_semana)]
display(df_dias_validos)

"""## Obtener los valores NO válidos de días de las semana"""

df_dias_validos = df[~df['dia_entrega'].apply(validar_dia_semana)]
display(df_dias_validos)

"""## Obtención de los elementos cuyos principios activos son correctos"""

df_principios_validos = df[df['principio_activo'].apply(
    lambda principio : validar_principios_activos(principios_activos, principio)
)]
display(df_principios_validos)

"""## Obtención de los elementos cuyos principios activos NO son correctos"""

df_principios_no_validos = df[~df['principio_activo'].apply(
    lambda principio : validar_principios_activos(principios_activos, principio)
)]
display(df_principios_no_validos)