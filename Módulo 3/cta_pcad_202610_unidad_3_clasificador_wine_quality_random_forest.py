# Obtención del df

# Une las características (X) y el objetivo (y) en un único DataFrame
df = pd.concat([wine_quality.data.features, wine_quality.data.targets], axis=1)

# Renombrado de columnas
df.rename(columns={
    'fixed_acidity': 'acidez_fija',
    'volatile_acidity': 'acidez_volatil',
    'citric_acid': 'acido_citrico',
    'residual_sugar': 'azucar_residual',
    'chlorides': 'cloruros',
    'free_sulfur_dioxide': 'dioxido_azufre_libre',
    'total_sulfur_dioxide': 'dioxido_azufre_total',
    'density': 'densidad',
    'pH': 'pH',
    'sulphates': 'sulfatos',
    'alcohol': 'alcohol',
    'quality': 'calidad'
}, inplace=True)

# Ver el resultado
display(df.head())

df.info()

